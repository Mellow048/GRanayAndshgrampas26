#!/usr/bin/env node
/**
 * Instant Episode Scaffolder CLI (`npm run new:episode`)
 *
 * Generates a clean, zero-error, `--strict`-ready starter gag or show scene
 * complete with a declarative `type: "custom"` prop example, physical arm acting
 * (`char_arm`), and smooth prop motion (`attach` / `glide`).
 *
 * Usage:
 *   npm run new:episode -- --name pizza_delivery --mode gag
 *   npm run new:episode -- --name morning_chaos --mode show
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (k, def = null) => {
  const i = args.indexOf(k);
  return i >= 0 && args[i + 1] ? args[i + 1] : def;
};

const rawName = flag("--name");
const mode = flag("--mode", "gag");

if (!rawName || !/^[a-z][a-zA-Z0-9_]*$/.test(rawName)) {
  console.error("Usage: npm run new:episode -- --name <camelOrSnakeName> --mode <gag|show>");
  process.exit(1);
}

const snake = rawName.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`);

if (mode === "gag") {
  const outPath = path.join(ROOT, "src", "gags", `${rawName}.js`);
  if (fs.existsSync(outPath)) {
    console.error(`File already exists: ${outPath}`);
    process.exit(1);
  }
  const code = `// Gag: "${rawName}" (~15s). Generated by \`npm run new:episode\` (FunnyHorrorAnimation v4 style).
import { lookAt, handItemTo, reactFast, placeOnSurface, playerReply } from "./helpers.js";

export function ${rawName}({ actorA = "granny", actorB = "grandpa" } = {}) {
  return {
    name: "${rawName}",
    duration: 15,
    room: "dining",
    playerSpawn: "dining_center",
    playerFacing: "dining_table_front",
    cast: {
      [actorA]: { spawn: "kitchen_lane", facing: "dining_table_front" },
      [actorB]: { spawn: "dining_table_front", facing: "kitchen_lane" },
    },
    props: [
      {
        id: "custom_gift",
        type: "custom",
        spawn: "dining_table_top",
        visible: true,
        parts: [
          { shape: "box", size: [0.3, 0.22, 0.3], pos: [0, 0.11, 0], color: 0xef4444 },
          { shape: "box", size: [0.32, 0.05, 0.06], pos: [0, 0.12, 0], color: 0xfacc15 },
          { shape: "box", size: [0.06, 0.05, 0.32], pos: [0, 0.12, 0], color: 0xfacc15 },
        ],
      },
    ],
    beats: [
      { at: 0.0, type: "bgm", sound: "fluffing_a_duck", volume: 0.22 },
      ...lookAt({ at: 0.0, target: actorA, duration: 0.3, track: true }),
      ...handItemTo({ at: 0.4, giver: actorA, receiver: actorB, prop: "custom_gift", targetHeight: "nose", duration: 2.2 }),
      ...lookAt({ at: 2.8, target: actorB, duration: 0.3, track: true }),
      ...reactFast({ at: 3.1, actor: actorB, emotion: "shock", duration: 1.0, sfx: "vine_boom" }),
      ...reactFast({ at: 4.3, actor: actorA, emotion: "sad", duration: 1.4, targetActor: actorB }),
      ...reactFast({ at: 6.0, actor: actorB, emotion: "offer", duration: 1.8, facePlayer: true, sfx: "pop" }),
      ...playerReply({ at: 7.4, lookTarget: actorB, gesture: "nod_yes", duration: 0.75 }),
      ...placeOnSurface({ at: 8.6, actor: actorA, prop: "custom_gift", to: "dining_table_top", duration: 1.0, sfx: "checkmark" }),
      ...lookAt({ at: 10.2, target: actorA, duration: 0.3, track: true }),
      ...reactFast({ at: 10.5, actor: actorA, emotion: "happy", duration: 1.6, facePlayer: true, sfx: "tada" }),
      ...playerReply({ at: 11.4, lookTarget: actorA, gesture: "nod_yes", duration: 0.8 }),
      { at: 13.6, type: "fade", to: 1, duration: 0.9 },
    ],
  };
}
`;
  fs.writeFileSync(outPath, code, "utf8");
  console.log(`Created gag: ${path.relative(ROOT, outPath)}`);
  console.log(`Next: export it in src/gags/index.js and verify with:`);
  console.log(`  npm run validate:episode -- --strict`);
} else if (mode === "show") {
  const dir = path.join(ROOT, "src", "shows", rawName);
  fs.mkdirSync(dir, { recursive: true });
  const scenePath = path.join(dir, "scene1-open.js");
  const idxPath = path.join(dir, "index.js");
  fs.writeFileSync(
    scenePath,
    `import { defineScene } from "../sceneKit.js";

export default defineScene({
  id: "open",
  title: "Opening Scene (2nd Floor Spawn Bedroom)",
  room: "upstairs_bedroom",
  duration: 12,
  playerSpawn: "up_bed_side",
  playerFacing: "up_bed_mattress",
  beats: [
    { at: 0.0, type: "bgm", sound: "granny_ambience", volume: 0.18 },
    { at: 0.0, type: "player_pose", pose: "lie", surface: "up_bed_mattress", roll: -0.24, pitch: 0.08, duration: 0.01 },
    { at: 1.4, type: "player_pose", pose: "stand", duration: 0.8 },
    { at: 2.4, type: "player_walk", to: "upstairs_landing", duration: 3.0, speed: 1.9 },
    { at: 5.8, type: "player_walk", to: "hall_corner", duration: 3.2, speed: 2.2 },
    { at: 9.4, type: "player_gesture", gesture: "nod_yes", duration: 0.8 },
    { at: 10.8, type: "fade", to: 1, duration: 0.8 },
  ],
});
`,
    "utf8"
  );
  fs.writeFileSync(
    idxPath,
    `import open from "./scene1-open.js";

export const ${snake.toUpperCase()} = {
  id: "${snake}",
  title: "${rawName}",
  aspect: "16:9",
  transitions: "continuous",
  scenes: [open],
};
`,
    "utf8"
  );
  console.log(`Created show: ${path.relative(ROOT, dir)}/`);
  console.log(`Next: register in src/shows/index.js and verify with:`);
  console.log(`  npm run validate:episode -- --show ${snake} --strict`);
} else {
  console.error(`Unknown --mode "${mode}". Use "gag" or "show".`);
  process.exit(1);
}
